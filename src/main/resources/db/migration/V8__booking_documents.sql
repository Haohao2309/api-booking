CREATE TABLE booking_documents (
 id BIGSERIAL PRIMARY KEY,booking_id BIGINT NOT NULL UNIQUE REFERENCES bookings(id),
 document_number VARCHAR(80) NOT NULL UNIQUE,storage_key VARCHAR(255) NOT NULL,
 booking_status VARCHAR(20) NOT NULL,content BYTEA NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
